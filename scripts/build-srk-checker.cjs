const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const ts = require('typescript');
const { Compiler } = require('ts-interface-builder');

const sourcePath = require.resolve('@algoux/standard-ranklist/index.d.ts');
const outputPath = path.resolve(__dirname, '../src/client/lib/srk-checker/index.d.ti.ts');
const program = ts.createProgram([sourcePath], { strictNullChecks: true, types: [] });
const sourceFile = program.getSourceFile(sourcePath);
const solution = sourceFile?.statements.find(
  (node) => ts.isInterfaceDeclaration(node) && node.name.text === 'Solution',
);
const result = solution?.members.find(
  (node) => ts.isPropertySignature(node) && node.name.getText(sourceFile) === 'result',
);

// ts-interface-builder 0.3.3 cannot compile Exclude. In SRK 0.3.14,
// Exclude<SolutionResultFull, null> | SolutionResultCustom is exactly string.
// Verify that equivalence with strict null checks before simplifying this field.
if (!result?.type || program.getTypeChecker().getTypeFromTypeNode(result.type).flags !== ts.TypeFlags.String) {
  throw new Error('SRK Solution.result no longer resolves to string; review the checker compatibility step.');
}
const sourceText = sourceFile.getFullText();
const compatibleSource =
  sourceText.slice(0, result.type.getStart(sourceFile)) + 'string' + sourceText.slice(result.type.end);
const temporaryDirectory = fs.mkdtempSync(path.join(os.tmpdir(), 'rankland-srk-checker-'));

try {
  const temporarySource = path.join(temporaryDirectory, 'index.d.ts');
  fs.writeFileSync(temporarySource, compatibleSource);
  const compiled = Compiler.compile(temporarySource);
  const header = '/**\n * This module was automatically generated by `ts-interface-builder`\n */\n';
  fs.writeFileSync(outputPath, header + compiled);
} finally {
  fs.rmSync(temporaryDirectory, { recursive: true, force: true });
}
